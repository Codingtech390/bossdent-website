export function getBlogBySlug(slug) {
  return sampleBlogs.find((blog) => blog.slug === slug) ?? null;
}

export function getReadingTime(blog) {
  if (blog.readTime) return blog.readTime;

  const words = (blog.content ?? [])
    .map((block) => [block.text, ...(block.items ?? [])].filter(Boolean).join(" "))
    .join(" ")
    .split(/\s+/)
    .filter(Boolean).length;

  return `${Math.max(1, Math.ceil(words / 200))} min read`;
}

export function getBlogDate(date) {
  return new Intl.DateTimeFormat("en-IN", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(date));
}
